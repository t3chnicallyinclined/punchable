//! Punchable's creative rules with no IO (docs/RUST.md step 1, part 1).
//!
//! The creative side of the app is a handful of append-only event logs (storyboards, working sets, venues, the job
//! queue, his account, merges, Ask conversations, intents, "not a joke" answers, the voice profile), each replayed
//! through its own reducer into the items the API serves. This crate holds the [`Store`] that replays and appends,
//! one [`Reducer`] per store with the Python's exact semantics and refusal texts ([`reducers`]), the verbatim gate
//! that keeps a model's quote only as an exact slice of its source ([`verbatim`]), the word normaliser the
//! transcript comparisons share ([`textdiff`]), and Ask, the conversation with his own notebook ([`ask`]: retrieve
//! the sources for a turn, build the prompt, gate the answer).
//!
//! Storage (files, `SurrealDB` `creative_event` rows) and HTTP live in other crates: a store takes lines in and hands
//! events out. The tests replay goldens generated by the Python it replaces (`rust/tools/gen_creative_goldens.py`).

pub mod ask;
pub mod error;
pub mod event;
pub mod pyish;
pub mod reducers;
pub mod store;
pub mod textdiff;
pub mod verbatim;

pub use ask::Notebook;
pub use error::{CreativeError, CreativeResult};
pub use event::Event;
pub use reducers::{STORES, for_store};
pub use store::{Items, Reducer, Store, parse_lines};
pub use textdiff::ntok;
pub use verbatim::verbatim;
